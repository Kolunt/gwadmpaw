"""
Scan templates/*.html for user-visible Russian text and append to generated registry.

Output: gwadm/_ui_string_registry_generated.py (imported by ui_string_registry).
"""

from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TEMPLATE_DIR = ROOT / "templates"

# Skip debug templates
SKIP_NAMES = frozenset({"debug.html", "debug_sign3.html"})

ATTR_RE = re.compile(
    r"(?:title|aria-label|placeholder|alt)=['\"]([^'\"]*[а-яА-ЯёЁ][^'\"]*)['\"]",
    re.IGNORECASE,
)
TEXT_RE = re.compile(r">([^<>]*)<")
BLOCK_TITLE_SIMPLE = re.compile(
    r"\{%\s*block\s+title\s*%\}\s*(.*?)\s*\{%\s*endblock\s*%\}",
    re.DOTALL | re.IGNORECASE,
)
# Already-wrapped Jinja: {{ _('...') }} or {{ _("...") }}
JINJA_UNDERSCORE = re.compile(
    r"\{\{[^}]*_\(\s*(['\"])(.+?)\1\s*\)[^}]*\}\}",
    re.DOTALL,
)

MAX_MSG_LEN = 400


def _strip_script_style(html: str) -> str:
    lower = html.lower()
    out = []
    pos = 0
    while pos < len(html):
        i_s = lower.find("<script", pos)
        i_t = lower.find("<style", pos)
        next_open = -1
        if i_s != -1 and i_t != -1:
            next_open = min(i_s, i_t)
        elif i_s != -1:
            next_open = i_s
        elif i_t != -1:
            next_open = i_t
        if next_open == -1:
            out.append(html[pos:])
            break
        out.append(html[pos:next_open])
        if lower[next_open : next_open + 7] == "<script":
            close = lower.find("</script>", next_open)
            if close == -1:
                break
            pos = close + len("</script>")
        else:
            close = lower.find("</style>", next_open)
            if close == -1:
                break
            pos = close + len("</style>")
    return "".join(out)


def _category_for(rel: Path) -> str:
    parts = rel.parts
    if not parts:
        return "misc"
    if parts[0] == "admin":
        if len(parts) > 1:
            return f"admin_{parts[1].replace('.html', '')}"
        return "admin"
    if parts[0] == "errors":
        return "errors"
    if parts[0] == "macros":
        return "macros"
    if parts[0] == "partials":
        return "partials"
    return parts[0].replace(".html", "") or "public"


def _clean(s: str) -> str | None:
    s = " ".join(s.split())
    if len(s) < 2:
        return None
    if len(s) > MAX_MSG_LEN:
        return None
    if not re.search(r"[а-яА-ЯёЁ]", s):
        return None
    if "{{" in s or "{%" in s or "}}" in s or "%}" in s:
        return None
    if s.startswith("http://") or s.startswith("https://"):
        return None
    return s


def extract_from_file(path: Path) -> set[str]:
    found: set[str] = set()
    text = path.read_text(encoding="utf-8")
    rel = path.relative_to(TEMPLATE_DIR)

    # Strip Jinja comments
    text = re.sub(r"\{#.*?#\}", "", text, flags=re.DOTALL)
    text = _strip_script_style(text)

    for m in ATTR_RE.finditer(text):
        c = _clean(m.group(1).strip())
        if c:
            found.add(c)

    # Between tags (rough): split by tags, take text parts
    for m in TEXT_RE.finditer(text):
        inner = m.group(1)
        if "{{" in inner or "{%" in inner:
            continue
        # Split on &nbsp; entities
        inner = inner.replace("&nbsp;", " ")
        c = _clean(inner.strip())
        if c and len(c) > 1:
            found.add(c)

    for m in BLOCK_TITLE_SIMPLE.finditer(text):
        inner = m.group(1).strip()
        if "{{" in inner or "{%" in inner:
            continue
        inner = inner.replace("&nbsp;", " ")
        c = _clean(inner)
        if c and len(c) > 1:
            found.add(c)

    for m in JINJA_UNDERSCORE.finditer(text):
        inner = m.group(2).strip()
        c = _clean(inner.replace("\\'", "'").replace('\\"', '"'))
        if c and len(c) > 1:
            found.add(c)
    return found


def main() -> None:
    by_category: dict[str, set[str]] = {}
    for path in sorted(TEMPLATE_DIR.rglob("*.html")):
        if path.name in SKIP_NAMES:
            continue
        rel = path.relative_to(TEMPLATE_DIR)
        cat = _category_for(rel)
        strings = extract_from_file(path)
        if not strings:
            continue
        by_category.setdefault(cat, set()).update(strings)

    # Flatten: one category per string — first category wins (deterministic order)
    all_strings: dict[str, str] = {}
    for cat in sorted(by_category.keys()):
        for s in sorted(by_category[cat]):
            if s not in all_strings:
                all_strings[s] = cat

    lines = [
        '"""AUTO-GENERATED by scripts/generate_ui_registry_from_templates.py — do not edit by hand."""',
        "",
        "# (msg_key, category, default_ru, default_en) — default_en = RU until translated in admin",
        "GENERATED_UI_STRINGS: list[tuple[str, str, str, str]] = [",
    ]
    for s in sorted(all_strings.keys(), key=lambda x: (all_strings[x], x)):
        cat = all_strings[s]
        # repr() escapes quotes safely
        lines.append(f"    ({repr(s)}, {repr(cat)}, {repr(s)}, {repr(s)}),")
    lines.append("]")
    lines.append("")

    out_path = ROOT / "gwadm" / "_ui_string_registry_generated.py"
    out_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {len(all_strings)} entries to {out_path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
